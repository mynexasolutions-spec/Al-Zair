export function getProductById(id: string): Product | undefined {
  return allProducts.find((p) => p.id === id || p.id.toLowerCase() === id.toLowerCase());
}

export function getRelatedProducts(currentId: string, category?: string, limit = 4): Product[] {
  const sameCategory = allProducts.filter((p) => p.id !== currentId && p.category === category);
  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit);
  }
  const others = allProducts.filter((p) => p.id !== currentId && p.category !== category);
  return [...sameCategory, ...others].slice(0, limit);
}

